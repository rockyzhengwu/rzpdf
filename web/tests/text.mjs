import assert from 'node:assert/strict';
import {searchPage,characterQuad} from '../dist/text.js';
const c=(unicode,position=[10,20],advance=[6,0])=>({unicode,position,advance,emToDisplay:[12,0,0,-12,...position],writingMode:'Horizontal'});
const page=(...text)=>({characters:text.map(t=>c(t))});
assert.deepEqual(searchPage(page('A',null,'B'),'AB'),[]);
assert.deepEqual(searchPage(page('A',null,'B'),'b'),[{start:2,end:3}]);
assert.deepEqual(searchPage(page('😀','fi','İ'),'😀fi'),[{start:0,end:2}]);
assert.deepEqual(searchPage(page('İ'),'i\u0307'),[{start:0,end:1}]);
assert.deepEqual(searchPage(page('a','a','a'),'a',false,2),[{start:0,end:1},{start:1,end:2}]);
assert.deepEqual(searchPage(page('A'),'a',true),[]);
assert.throws(()=>searchPage(page('a'),''));
assert.throws(()=>searchPage(page('a'),null));
assert.throws(()=>searchPage(page('a'),'a','false'));
assert.throws(()=>searchPage(page('a'),'\0'));
assert.throws(()=>searchPage(page('a'),'a',false,0));
assert.equal(characterQuad({...c('a'),emToDisplay:null}),null);
const q=characterQuad(c('a'));assert.equal(q.length,8);assert.equal(q[2]-q[0],6);assert.equal(q[7]-q[1],12);
const rotated=characterQuad({...c('a',[20,10],[0,6]),emToDisplay:[0,12,12,0,20,10]});
assert.equal(rotated[3]-rotated[1],6);assert.equal(rotated[6]-rotated[0],-12);
console.log('Text search and logical geometry checks passed');
